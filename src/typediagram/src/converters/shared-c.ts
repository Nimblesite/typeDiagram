// [CONV-SHARED-C] Constants-only C profile emitted from generateSharedLayout — never recomputes layouts.
import type { Model } from "../model/types.js";
import type { Diagnostic } from "../parser/diagnostics.js";
import { err, ok, type Result } from "../result.js";
import { generateSharedLayout } from "./shared-layout.js";

const IDENTIFIER = /^[A-Za-z_][A-Za-z0-9_]*$/;
type SharedManifest = Extract<Awaited<ReturnType<typeof generateSharedLayout>>, { ok: true }>["value"];
type LayoutDecl = SharedManifest["declarations"][number];
type LayoutField = NonNullable<LayoutDecl["fields"]>[number];
type LayoutVariant = NonNullable<LayoutDecl["variants"]>[number];

const failure = (message: string) =>
  err<Diagnostic[]>([{ severity: "error", message: `shared-c: ${message}`, line: 0, col: 0, length: 0 }]);

/** Parser identifiers are already `[A-Za-z_][A-Za-z0-9_]*`; this guards hand-built models from injecting C. */
const badIdentifier = (kind: string, name: string) =>
  IDENTIFIER.exec(name)?.[0] === name ? undefined : `invalid C identifier for ${kind} '${name}'`;

const validateIdentifiers = (manifest: SharedManifest): Result<true, Diagnostic[]> => {
  const bad = [
    ...manifest.declarations.map((decl) => badIdentifier("declaration", decl.name)),
    ...manifest.declarations.flatMap((decl) => [
      ...(decl.fields ?? []).map((field) => badIdentifier(`field of '${decl.name}'`, field.name)),
      ...(decl.variants ?? []).flatMap((variant) => [
        badIdentifier(`variant of '${decl.name}'`, variant.name),
        ...variant.fields.map((field) => badIdentifier(`field of '${decl.name}.${variant.name}'`, field.name)),
      ]),
    ]),
  ].find((message) => message !== undefined);
  return bad === undefined ? ok(true) : failure(bad);
};

const fieldMacros = (owner: string, field: LayoutField) => [
  `#define TD_${owner}_${field.name}_OFFSET ${String(field.offset)}`,
  `#define TD_${owner}_${field.name}_BYTES ${String(field.bytes)}`,
];

const variantMacros = (decl: string, variant: LayoutVariant) => [
  `#define TD_${decl}_${variant.name}_TAG ${String(variant.tag)}`,
  ...variant.fields.flatMap((field) => fieldMacros(`${decl}_${variant.name}`, field)),
];

const declarationLines = (decl: LayoutDecl): Result<string[], Diagnostic[]> =>
  decl.bytes === 0
    ? failure(`zero-size declaration '${decl.name}' cannot be emitted`)
    : ok([
        `TD_SHARED_STORAGE(${decl.name}, ${String(decl.bytes)});`,
        ...(decl.fields ?? []).flatMap((field) => fieldMacros(decl.name, field)),
        ...(decl.variants ?? []).flatMap((variant) => variantMacros(decl.name, variant)),
      ]);

const prologue = (manifest: SharedManifest) => [
  "// Generated by typeDiagram shared-memory profile. Constants only: no pointers, accessors, codec, or view validation.",
  "#ifndef TD_SHARED_H",
  "#define TD_SHARED_H",
  "#include <stddef.h>",
  `#define TD_SHARED_FINGERPRINT "${manifest.fingerprint}"`,
  `#define TD_SHARED_POINTER_BYTES ${String(manifest.pointerBytes)}`,
  `#define TD_SHARED_ABI_MAJOR ${String(manifest.abiMajor)}`,
  "#define TD_SHARED_STORAGE(name, byte_count) \\",
  `  typedef struct { _Alignas(${String(manifest.alignment)}) unsigned char bytes[byte_count]; } td_##name; \\`,
  `  _Static_assert(sizeof(td_##name) == (byte_count) && _Alignof(td_##name) == ${String(manifest.alignment)}, #name " size/alignment")`,
];

const symbols = (decl: LayoutDecl) => [
  `td_${decl.name}`,
  ...(decl.fields ?? []).flatMap((f) => [`TD_${decl.name}_${f.name}_OFFSET`, `TD_${decl.name}_${f.name}_BYTES`]),
  ...(decl.variants ?? []).flatMap((v) => [
    `TD_${decl.name}_${v.name}_TAG`,
    ...v.fields.flatMap((f) => [
      `TD_${decl.name}_${v.name}_${f.name}_OFFSET`,
      `TD_${decl.name}_${v.name}_${f.name}_BYTES`,
    ]),
  ]),
];
const validateSymbols = (manifest: SharedManifest, names?: readonly string[]) => {
  const identifiers = validateIdentifiers(manifest);
  if (!identifiers.ok) {
    return identifiers;
  }
  const all = manifest.declarations.flatMap(symbols);
  if (new Set(all).size !== all.length) {
    return failure("C symbol collision after name composition");
  }
  const missing = names?.find((name) => !manifest.declarations.some((d) => d.name === name));
  return missing === undefined ? ok(true) : failure(`unknown declaration '${missing}'`);
};
const emitHeader = (manifest: SharedManifest, names?: readonly string[]) => {
  const lines: string[] = prologue(manifest);
  for (const decl of manifest.declarations.filter((d) => names === undefined || names.includes(d.name))) {
    const body = declarationLines(decl);
    if (!body.ok) {
      return body;
    }
    lines.push(...body.value);
  }
  return ok([...lines, "", "#undef TD_SHARED_STORAGE", "#endif"].join("\n"));
};
/** Emit C storage/constants from the complete layout identity, optionally selecting declarations. */
export const generateSharedC = async (model: Model, pointerBytes: number, names?: readonly string[]) => {
  const layout = await generateSharedLayout(model, pointerBytes);
  if (!layout.ok) {
    return layout;
  }
  const valid = validateSymbols(layout.value, names);
  return valid.ok ? emitHeader(layout.value, names) : valid;
};
